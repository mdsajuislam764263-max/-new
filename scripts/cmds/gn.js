// =====================================================
// GN COMMAND
// =====================================================

module.exports.onStart = async function ({ api, event }) {

    try {

        let msg = `╔══════════════════╗
      🦋 𝑮𝑪 𝑵𝑨𝑴𝑬 𝑳𝑰𝑺𝑻 🦋
╚══════════════════╝

`;

        for (let i = 0; i < NAMES.length; i++) {
            msg += `【${i + 1}】 ${NAMES[i]}\n\n`;
        }

        msg += `━━━━━━━━━━━━━━━━━━
💬 যেই নাম নিতে চাও
এই মেসেজে Reply করে শুধু Number দাও।

উদাহরণ:
1
2
3
━━━━━━━━━━━━━━━━━━`;

        const sent = await api.sendMessage(
            msg,
            event.threadID
        );

        if (!sent || !sent.messageID) {
            return;
        }

        /*
         * IMPORTANT
         * handlerEvents.js এই Map থেকেই Reply নেয়।
         */
        if (
            global.GoatBot &&
            global.GoatBot.onReply &&
            typeof global.GoatBot.onReply.set === "function"
        ) {

            global.GoatBot.onReply.set(
                sent.messageID,
                {
                    commandName: "gn",
                    messageID: sent.messageID,
                    author: event.senderID,
                    names: NAMES
                }
            );

        } else {

            console.log(
                "[GN] GoatBot.onReply Map পাওয়া যায়নি!"
            );

        }

    } catch (error) {

        console.error(
            "[GN] onStart Error:",
            error
        );

    }
};


// =====================================================
// REPLY HANDLER
// =====================================================

module.exports.onReply = async function ({
    api,
    event,
    Reply
}) {

    try {

        // Reply data না থাকলে কিছু করবে না
        if (!Reply) return;

        // names না থাকলে কিছু করবে না
        if (!Array.isArray(Reply.names)) return;

        // User যে text দিয়েছে
        const text = String(
            event.body || ""
        ).trim();

        // শুধু Number হলে কাজ করবে
        if (!/^\d+$/.test(text)) {
            return;
        }

        const number = Number(text);

        // Number range check
        if (
            number < 1 ||
            number > Reply.names.length
        ) {

            return api.sendMessage(
                `❌ ভুল Number!\n\nশুধু 1 থেকে ${Reply.names.length} এর মধ্যে Number দাও।`,
                event.threadID
            );

        }

        // Selected name
        const selectedName =
            Reply.names[number - 1];

        // ⭐ শুধু নাম পাঠাবে
        return api.sendMessage(
            selectedName,
            event.threadID
        );

    } catch (error) {

        console.error(
            "[GN] onReply Error:",
            error
        );

    }
};
